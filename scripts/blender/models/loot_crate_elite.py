"""Элитный ящик: стальной военный контейнер (зелёный по металлу), выштампованные рёбра, усиленные углы,
навесной замок, жёлто-чёрная полоса «опасно / ценно»."""
from _crate import H, L, W, handles


def build(k):
    k.box((L, W, H - 0.12), (0, 0, 0), "paint_green", bevel=0.02)
    k.box((L + 0.014, W + 0.014, 0.12), (0, 0, H - 0.12), "paint_green", bevel=0.022)
    for x in (-0.28, 0.0, 0.28):                                           # выштамповка на крышке
        k.box((0.12, W - 0.12, 0.018), (x, 0, H), "paint_green", bevel=0.008)
    for x in (-L / 2 + 0.01, L / 2 - 0.01):                                 # усиленные углы
        for y in (-W / 2 + 0.005, W / 2 - 0.005):
            k.box((0.06, 0.06, H + 0.01), (x, y, 0), "steel", bevel=0.006)
    for i in range(4):                                                      # полоса: жёлтый-чёрный
        k.box((0.1, 0.006, 0.05), (-0.3 + i * 0.1, -W / 2 - 0.004, 0.08), "yellow" if i % 2 == 0 else "black", bevel=0.0)
    k.box((0.07, 0.02, 0.1), (0, -W / 2 - 0.012, H - 0.17), "steel", bevel=0.005)    # проушина
    k.box((0.07, 0.03, 0.07), (0, -W / 2 - 0.03, H - 0.24), "rust_dark", bevel=0.008)  # замок
    handles(k, 0.3)
    k.stencil("ОСОБО ЦЕННО", (0.0, -W / 2, 0.22), size=0.04)
