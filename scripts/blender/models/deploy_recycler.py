"""Переработчик (стоит на РТ) — по 2D-спрайту recycler: зелёная промышленная дробилка, широкий бункер с
валками-ножами, жёлто-чёрная полоса над окном выдачи, наклонный лоток спереди, моторы по бокам, пульт.
1,63 × 1,2 × 1,95."""


def build(k):
    L, W = 1.6, 1.18
    k.box((L, W, 0.1), (0, 0, 0), "rust_dark", bevel=0.01)                                     # рама
    k.box((1.0, 0.9, 1.05), (0, 0.05, 0.1), "paint_green", bevel=0.02)                          # корпус
    hop = k.cyl(0.62, 0.6, (0, 0.05, 1.15), "paint_green", segments=4, bevel=0.01, radius_top=0.82, shell=0.03)   # бункер
    hop.rotation_euler.z = 0.785
    k.box((0.86, 0.66, 0.02), (0, 0.05, 1.2), "black", bevel=0)                                 # провал
    for i in range(4):                                                                          # валки-ножи
        x = -0.3 + i * 0.2
        k.cyl(0.07, 0.6, (x, -0.25, 1.28), "steel", segments=10, axis="Y", bevel=0.004)
        for j in range(3):
            k.box((0.04, 0.03, 0.17), (x, -0.15 + j * 0.2, 1.2), "rust", bevel=0.003)
    k.box((0.7, 0.04, 0.4), (0, -0.405, 0.42), "black", bevel=0)                                # окно выдачи
    for i in range(7):                                                                          # полоса над окном
        k.box((0.1, 0.006, 0.07), (-0.3 + i * 0.1, -0.405, 0.85), "yellow" if i % 2 == 0 else "black", bevel=0)
    lt = k.box((0.7, 0.45, 0.03), (0, 0, 0), "steel", bevel=0.006)                             # лоток
    lt.rotation_euler.x = -0.35
    lt.location = (0, -0.38, 0.38)
    for x in (-0.36, 0.36):
        k.box((0.03, 0.42, 0.12), (x, -0.6, 0.15), "steel", bevel=0.004)
    for x in (-0.75, 0.5):                                                                      # моторы по бокам
        k.cyl(0.16, 0.25, (x, 0.15, 0.55), "paint_blue", segments=14, axis="X", bevel=0.01)
    k.box((0.22, 0.12, 0.35), (0.68, -0.35, 0.1), "paint_green", bevel=0.01)                    # пульт
    k.cyl(0.03, 0.03, (0.68, -0.44, 0.38), "red", segments=10, axis="Y", bevel=0.003)
    k.stencil("ПЕРЕРАБОТКА", (0, -0.41, 0.97), size=0.05)
