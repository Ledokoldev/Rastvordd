"""Электропечь — по 2D-спрайту efurnace: широкая коробчатая печь из листовой стали на рёбрах, спереди
заслонка с раскалённой щелью (акцент), на своде патрубок и кабельные вводы, справа шкаф управления.
Квадратный след 1,85."""


def build(k):
    k.box((1.8, 1.4, 0.1), (0, 0.15, 0), "rust_dark", bevel=0.01)                              # рама
    k.box((1.25, 1.2, 1.0), (-0.25, 0.15, 0.1), "paint_blue", bevel=0.02)                       # корпус
    for x in (-0.82, -0.45, -0.05, 0.32):                                                       # рёбра
        k.box((0.06, 1.24, 1.02), (x, 0.15, 0.1), "steel", bevel=0.006)
    k.box((1.3, 1.25, 0.08), (-0.25, 0.15, 1.1), "rust_dark", bevel=0.012)                      # свод
    k.cyl(0.14, 0.3, (-0.45, 0.3, 1.18), "rust_dark", segments=12, bevel=0.008)                 # патрубок
    for x in (-0.05, 0.15):                                                                      # кабельные вводы
        k.cyl(0.04, 0.16, (x, 0.0, 1.18), "clean_black", segments=8, bevel=0.004)
    # заслонка спереди
    k.box((0.8, 0.06, 0.45), (-0.25, -0.47, 0.3), "rust", bevel=0.01)
    k.box((0.6, 0.02, 0.07), (-0.25, -0.505, 0.47), "glow", bevel=0)                            # щель
    k.box((0.5, 0.04, 0.03), (-0.25, -0.51, 0.62), "steel", bevel=0.004)                        # ручка
    # шкаф управления справа
    k.box((0.45, 0.7, 1.1), (0.62, 0.25, 0.1), "paint_blue", bevel=0.015)
    for i in range(5):
        k.box((0.3, 0.02, 0.025), (0.62, -0.105, 0.45 + i * 0.08), "steel", bevel=0.003)       # жалюзи
    k.box((0.14, 0.02, 0.1), (0.62, -0.105, 0.95), "glass", bevel=0.003)                        # прибор
    k.stencil("380 В", (0.62, -0.112, 0.25), size=0.05)
