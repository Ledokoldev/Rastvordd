"""Спальник: брезентовый мешок хаки на подстилке-пенке, валик в изголовье, молния, два ремня. 1,9 × 0,75."""


def build(k):
    k.box((1.88, 0.74, 0.02), (0, 0, 0), "rubber", bevel=0.005)                               # пенка
    k.box((1.6, 0.66, 0.14), (-0.1, 0, 0.02), "cloth", bevel=0.06)                            # мешок
    k.box((1.3, 0.6, 0.06), (-0.2, 0, 0.12), "cloth", bevel=0.03)                              # верх
    k.cyl(0.11, 0.66, (0.78, -0.33, 0.02), "cloth_grey", segments=14, axis="Y", bevel=0.02)   # валик-подушка
    k.box((1.4, 0.015, 0.01), (-0.15, -0.2, 0.17), "black", bevel=0)                           # молния
    for x in (-0.6, 0.1):                                                                       # ремни
        k.box((0.04, 0.7, 0.012), (x, 0, 0.17), "rubber", bevel=0)
