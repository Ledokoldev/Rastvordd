"""Оружейный стол: тяжёлый стальной верстак в зелёной краске, тумба с ящиками, перфощит с ключами, тиски,
разобранный автомат, цинк с патронами. Квадратный след 1,85."""


def build(k):
    L, W, H = 1.8, 1.0, 0.85
    y0 = 0.35                                                                                  # стол у задней кромки
    k.box((L, W, 0.06), (0, y0, H - 0.06), "steel", bevel=0.01)
    for x in (-L / 2 + 0.06, L / 2 - 0.06):
        k.box((0.08, W - 0.08, H - 0.06), (x, y0, 0), "paint_green", bevel=0.01)              # боковины
    k.box((0.5, W - 0.1, H - 0.1), (-0.55, y0, 0.02), "paint_green", bevel=0.012)              # тумба
    for i in range(3):
        k.box((0.44, 0.02, 0.2), (-0.55, y0 - W / 2 + 0.04, 0.08 + i * 0.24), "paint_green", bevel=0.006)
        k.box((0.12, 0.02, 0.02), (-0.55, y0 - W / 2 + 0.02, 0.2 + i * 0.24), "steel", bevel=0.003)
    k.box((L - 0.1, 0.04, 0.8), (0, y0 + W / 2 - 0.05, H), "plywood", bevel=0.006)            # перфощит
    for x, h in ((-0.6, 0.3), (-0.4, 0.25), (0.5, 0.35), (0.65, 0.2)):
        k.box((0.04, 0.03, h), (x, y0 + W / 2 - 0.09, H + 0.35), "rust", bevel=0.004)          # ключи, напильники
    k.box((0.14, 0.2, 0.1), (0.65, y0 - 0.32, H), "paint_blue", bevel=0.01)                    # тиски
    k.box((0.16, 0.04, 0.1), (0.65, y0 - 0.44, H + 0.04), "paint_blue", bevel=0.008)
    k.cyl(0.012, 0.22, (0.65, y0 - 0.56, H + 0.08), "steel", segments=8, axis="Y", bevel=0)
    # разобранный автомат: коробка, ствол, приклад, магазин
    k.box((0.24, 0.05, 0.06), (0.05, y0 - 0.15, H), "clean_black", bevel=0.006)
    k.cyl(0.012, 0.42, (0.17, y0 - 0.15, H + 0.03), "clean_black", segments=8, axis="X", bevel=0)
    k.box((0.2, 0.05, 0.05), (-0.18, y0 - 0.12, H), "wood_dark", rot_z=0.1, bevel=0.01)
    k.box((0.08, 0.035, 0.18), (0.0, y0 - 0.3, H), "brass", rot_z=0.5, bevel=0.006)
    k.box((0.3, 0.18, 0.12), (0.4, y0 + 0.15, H), "paint_green", bevel=0.01)                  # цинк
    k.stencil("7,62", (0.4, y0 + 0.15, H + 0.12), size=0.05, facing="+Z")
