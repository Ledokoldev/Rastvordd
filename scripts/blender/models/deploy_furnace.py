"""Буржуйка: сварной ящик из толстого чёрного металла с ржавчиной на четырёх ножках, топочная дверца с ручкой,
поддувало, труба вверх с коленом. Корпус 0,6 × 0,45 × 0,5 м, с трубой — 1,5 м."""


def build(k):
    L, W, H = 0.6, 0.45, 0.48
    legs = 0.14
    for x in (-L / 2 + 0.05, L / 2 - 0.05):
        for y in (-W / 2 + 0.05, W / 2 - 0.05):
            k.box((0.04, 0.04, legs + 0.02), (x, y, 0), "rust_dark", bevel=0.005)
    body_z = legs
    k.box((L, W, H), (0, 0, body_z), "rust_dark", bevel=0.015)
    k.box((L + 0.03, W + 0.03, 0.02), (0, 0, body_z + H), "rust_dark", bevel=0.006)    # верхний лист с выступом
    # топочная дверца на передней стороне (−Y), петли, ручка
    k.box((0.26, 0.02, 0.2), (0.06, -W / 2 - 0.01, body_z + 0.2), "rust", bevel=0.006)
    k.box((0.03, 0.025, 0.05), (-0.085, -W / 2 - 0.012, body_z + 0.22), "steel", bevel=0.004)
    k.box((0.03, 0.025, 0.05), (-0.085, -W / 2 - 0.012, body_z + 0.33), "steel", bevel=0.004)
    k.cyl(0.012, 0.08, (0.17, -W / 2 - 0.03, body_z + 0.3), "steel", segments=8, axis="Y", bevel=0)
    # поддувало — щель снизу
    k.box((0.22, 0.02, 0.06), (0.06, -W / 2 - 0.01, body_z + 0.07), "black", bevel=0.003)
    # труба: вверх от задней части, колено, ещё вверх
    px, py = -0.15, 0.08
    k.cyl(0.065, 0.06, (px, py, body_z + H + 0.02), "rust_dark", segments=16, bevel=0.004)   # фланец
    k.cyl(0.055, 0.55, (px, py, body_z + H + 0.02), "rust_dark", segments=14, bevel=0)
    k.cyl(0.062, 0.03, (px, py, body_z + H + 0.3), "rust", segments=14, bevel=0)             # хомут
    k.cyl(0.055, 0.35, (px, py, body_z + H + 0.57), "rust_dark", segments=14, bevel=0)
