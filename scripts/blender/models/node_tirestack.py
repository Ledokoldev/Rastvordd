"""Стопка покрышек (ресурс) — по 2D-спрайту gar_tire_stack: четыре лысые покрышки друг на друге,
чуть вразнобой, пятая прислонена сбоку. 0,84 × 0,82 × 0,66 м."""


def build(k):
    R, r = 0.26, 0.075
    offs = ((0, 0), (0.025, -0.02), (-0.02, 0.015), (0.015, 0.02))
    for i, (dx, dy) in enumerate(offs):
        k.torus(R, r, (dx - 0.08, dy, r + i * 0.135), "rubber", seg=22, ring=8, tread=0.6)
    t = k.torus(R, r, (0.0, 0.0, 0.0), "rubber", seg=22, ring=8, tread=0.6, rot=(0, 1.25, 0))   # прислонённая
    t.location = (0.27, 0.05, R + 0.02)
