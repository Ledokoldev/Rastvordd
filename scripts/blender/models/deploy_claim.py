"""Шкаф (право на землю) — по 2D-спрайту claim_post: вкопанный обветренный столб, красная тряпка-флаг
на верхушке, жестяной ящичек-коробка с замком на столбе, скобы-хомуты. Акцент — красная ткань. 0,65 × 0,5 × 1,8 м."""
import math


def build(k):
    k.cyl(0.11, 1.75, (0, 0, 0), "planks", segments=10, bevel=0.012, radius_top=0.095)        # столб
    k.cyl(0.18, 0.06, (0, 0, 0), "concrete", segments=10, bevel=0.01, radius_top=0.13)         # подсыпка
    for z in (0.35, 1.3):                                                                       # хомуты
        k.cyl(0.112, 0.035, (0, 0, z), "rust", segments=10, bevel=0.004)
    k.box((0.2, 0.08, 0.26), (0, -0.14, 0.95), "paint_green", bevel=0.01)                       # ящичек
    k.box((0.04, 0.02, 0.05), (0, -0.19, 1.02), "brass", bevel=0.005)                           # замок
    k.stencil("№ 1", (0, -0.18, 0.95 + 0.07), size=0.035)
    # красная тряпка: узел и два хвоста, свисающих на ветру
    k.cyl(0.1, 0.07, (0, 0, 1.55), "red", segments=10, bevel=0.01)
    for i, (dx, ln, a) in enumerate(((0.12, 0.38, 0.5), (0.1, 0.28, 0.9))):
        ob = k.box((0.1, 0.012, ln), (0, 0, 0), "red", bevel=0.004)
        ob.rotation_euler = (0, math.pi - a, -0.3 + i * 0.5)
        ob.location = (dx * 0.6, -0.02 + i * 0.03, 1.6)
