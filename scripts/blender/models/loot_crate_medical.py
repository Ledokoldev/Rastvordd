"""Медицинский ящик: светлый крашеный металл, рёбра жёсткости, красный крест на крышке и спереди (акцент)."""
from _crate import H, L, W, handles, latches


def build(k):
    h = H - 0.04
    k.box((L, W, h - 0.1), (0, 0, 0), "white", bevel=0.015)
    k.box((L + 0.012, W + 0.012, 0.1), (0, 0, h - 0.1), "white", bevel=0.018)
    k.box((L + 0.016, W + 0.016, 0.03), (0, 0, h - 0.12), "steel", bevel=0.006)        # шов крышки
    for x in (-0.3, 0.0, 0.3):                                                           # рёбра на бортах
        k.box((0.04, W + 0.012, 0.3), (x, 0, 0.08), "white", bevel=0.008)
    k.box((0.26, 0.07, 0.004), (0.05, 0, h), "red", bevel=0.0)                           # крест на крышке
    k.box((0.07, 0.26, 0.006), (0.05, 0, h), "red", bevel=0.0)     # чуть выше первой — без z-fighting
    k.box((0.16, 0.004, 0.045), (-0.25, -W / 2 - 0.004, 0.2), "red", bevel=0.0)          # крест спереди
    k.box((0.045, 0.006, 0.16), (-0.25, -W / 2 - 0.004, 0.142), "red", bevel=0.0)
    handles(k, 0.3)
    latches(k, h - 0.15)
    k.stencil("АПТЕЧКА", (0.14, -W / 2 - 0.006, 0.2), size=0.05, material="red")
