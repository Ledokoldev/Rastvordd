"""Бочка 200 л на обочине (ресурс): стальная, защитный зелёный с ржавчиной, два обруча-зига, закатанные края,
две пробки на крышке. Ø 0,58 × 0,88 м (как старая модель)."""


def build(k):
    r, h = 0.29, 0.88
    k.cyl(r, h, (0, 0, 0), "paint_green", segments=20, bevel=0.01)
    for z in (0.0, h - 0.028):                                   # закатанные края (верх обода ниже крышки — без z-fighting)
        k.cyl(r + 0.012, 0.025, (0, 0, z), "rust", segments=20, bevel=0.004)
    for z in (h * 0.33, h * 0.66):                               # обручи
        k.cyl(r + 0.01, 0.03, (0, 0, z), "paint_green", segments=20, bevel=0.006)
    k.cyl(0.035, 0.02, (0.16, 0.06, h), "steel", segments=10, bevel=0.003)   # пробки
    k.cyl(0.022, 0.02, (-0.16, -0.08, h), "steel", segments=8, bevel=0.003)
    k.stencil("ОГНЕОПАСНО", (0, -r - 0.004, h * 0.5), size=0.045, wrap=r + 0.004)
