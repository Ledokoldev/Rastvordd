"""Медстол: белый металлический стол-кушетка, шкафчик с красным крестом, бикс, стойка капельницы.
След 1,7 × 0,85."""
from _table import table


def build(k):
    H = 0.78
    table(k, top="white", frame="white", H=H)
    k.box((1.0, 0.7, 0.05), (0.25, 0, H), "cloth", bevel=0.02)                               # клеёнка-матрас
    k.box((0.25, 0.6, 0.08), (0.62, 0, H + 0.05), "cloth", bevel=0.03)                        # валик
    k.box((0.48, 0.36, 0.6), (-0.55, 0.12, H), "white", bevel=0.015)                          # шкафчик
    for x in (-0.66, -0.44):
        k.box((0.2, 0.02, 0.5), (x, -0.065, H + 0.05), "white", bevel=0.006)                  # дверцы
    k.box((0.16, 0.006, 0.05), (-0.55, -0.078, H + 0.38), "red", bevel=0)                      # крест
    k.box((0.05, 0.008, 0.16), (-0.55, -0.078, H + 0.325), "red", bevel=0)
    k.cyl(0.08, 0.1, (-0.1, -0.2, H), "steel", segments=14, bevel=0.006)                      # бикс
    k.cyl(0.012, 1.0, (0.78, 0.33, H), "steel", segments=8, bevel=0)                          # стойка
    k.box((0.2, 0.012, 0.012), (0.78, 0.33, H + 1.0), "steel", bevel=0)
    k.cyl(0.04, 0.12, (0.7, 0.33, H + 0.86), "glass", segments=10, bevel=0.005)
    k.stencil("ГО", (-0.55, -0.078, H + 0.2), size=0.04, material="red")
