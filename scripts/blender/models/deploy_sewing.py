"""Швейный стол — по 2D-спрайту sewing: дощатая столешница на чугунных ножных станинах с педалью
(как у старых «Зингеров»), чёрная машинка с латунным маховиком, рулоны и обрезки ткани. След 1,7 × 0,85."""
import math


def build(k):
    L, W, H = 1.66, 0.8, 0.8
    k.box((L, W, 0.05), (0, 0, H - 0.05), "planks", bevel=0.01)                                 # столешница
    k.box((0.5, W - 0.1, 0.12), (0.5, 0, H - 0.17), "planks", bevel=0.008)                      # ящик справа
    for x in (-0.7, 0.2):                                                                         # чугунные станины
        for y in (-0.3, 0.3):
            k.box((0.05, 0.05, H - 0.05), (x, y, 0), "clean_black", rot_z=0, bevel=0.01)
        k.box((0.05, 0.66, 0.06), (x, 0, 0.0), "clean_black", bevel=0.01)                         # лапа
        k.box((0.04, 0.6, 0.04), (x, 0, H - 0.12), "clean_black", bevel=0.008)
        k.cyl(0.18, 0.025, (x, -0.0125, 0.42), "clean_black", segments=12, axis="Y", bevel=0.004)   # колесо-лира
    k.box((0.8, 0.04, 0.04), (-0.25, 0.28, 0.12), "clean_black", bevel=0.008)                     # стяжка
    k.box((0.5, 0.3, 0.025), (-0.25, -0.02, 0.1), "clean_black", rot_z=0, bevel=0.006)           # педаль
    # машинка
    k.box((0.42, 0.2, 0.04), (-0.25, 0.05, H), "clean_black", bevel=0.01)
    k.box((0.07, 0.12, 0.2), (-0.05, 0.05, H + 0.04), "clean_black", bevel=0.02)
    k.box((0.36, 0.1, 0.08), (-0.2, 0.05, H + 0.2), "clean_black", bevel=0.025)
    k.box((0.06, 0.08, 0.16), (-0.38, 0.05, H + 0.1), "clean_black", bevel=0.015)
    k.cyl(0.07, 0.025, (-0.0, 0.13, H + 0.17), "brass", segments=16, axis="Y", bevel=0.004)
    k.box((0.12, 0.12, 0.004), (-0.36, -0.04, H + 0.04), "steel", bevel=0)
    k.stencil("ЧАЙКА", (-0.2, 0.0, H + 0.24), size=0.025, material="brass")
    for i, y in enumerate((-0.15, 0.17)):                                                        # рулоны
        k.cyl(0.08 - i * 0.015, 0.45, (0.3, y, H + 0.08 - i * 0.015), "cloth", segments=14, axis="X", bevel=0.01)
    k.box((0.35, 0.28, 0.008), (0.45, -0.1, H), "cloth", rot_z=0.15, bevel=0)
    k.box((0.16, 0.02, 0.006), (0.05, -0.28, H), "steel", rot_z=math.radians(30), bevel=0)      # ножницы
