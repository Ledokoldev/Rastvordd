"""Большой сундук-ларь: доски, две железные полосы-оковки вокруг, петли сзади, проушина под замок спереди,
ручки по бокам. 1,4 × 0,8 × 0,8 м."""


def build(k):
    L, W, H = 1.4, 0.8, 0.78
    lid = 0.12
    k.box((L, W, H - lid), (0, 0, 0), "planks", bevel=0.01)
    k.box((L + 0.02, W + 0.02, lid), (0, 0, H - lid), "planks", bevel=0.012)
    for x in (-0.42, 0.42):                                                    # оковки
        k.box((0.06, W + 0.03, H - lid - 0.02), (x, 0, 0.01), "rust", bevel=0.004)
        k.box((0.06, W + 0.04, lid), (x, 0, H - lid), "rust", bevel=0.004)
        k.box((0.06, W + 0.04, 0.012), (x, 0, H), "rust", bevel=0.003)
    for x in (-0.45, 0.45):                                                    # петли сзади
        k.box((0.12, 0.02, 0.1), (x + 0.1, W / 2 + 0.015, H - lid - 0.04), "steel", bevel=0.004)
    k.box((0.06, 0.03, 0.12), (0, -W / 2 - 0.02, H - lid - 0.07), "steel", bevel=0.004)    # проушина
    k.box((0.04, 0.025, 0.06), (0, -W / 2 - 0.035, H - lid - 0.1), "black", bevel=0.004)   # замок
    for s in (-1, 1):                                                          # ручки
        k.box((0.025, 0.24, 0.025), (s * (L / 2 + 0.045), 0, 0.42), "steel", bevel=0.005)
        for y in (-0.11, 0.11):
            k.box((0.04, 0.02, 0.025), (s * (L / 2 + 0.02), y, 0.42), "steel", bevel=0.004)
