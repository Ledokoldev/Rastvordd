"""Общий стол-станция: столешница на четырёх ногах с нижней полкой. Половинный след 1,7 × 0,85 м."""


def table(k, L=1.66, W=0.8, H=0.82, top="planks", frame="paint_blue", shelf=True):
    k.box((L, W, 0.05), (0, 0, H - 0.05), top, bevel=0.01)
    for x in (-L / 2 + 0.05, L / 2 - 0.05):
        for y in (-W / 2 + 0.05, W / 2 - 0.05):
            k.box((0.05, 0.05, H - 0.05), (x, y, 0), frame, bevel=0.006)
    k.box((L - 0.06, 0.04, 0.05), (0, -W / 2 + 0.05, H - 0.11), frame, bevel=0.005)   # царга спереди
    if shelf:
        k.box((L - 0.1, W - 0.1, 0.03), (0, 0, 0.16), "plywood", bevel=0.006)
