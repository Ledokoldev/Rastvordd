"""Армейский ящик: корпус из зелёных досок, обвязка-рейки по торцам, железные уголки,
железные ручки-скобы на торцах и защёлки на крышке. Акцент — жёлтая полоса (ценное). 0,9 × 0,5 × 0,42 м."""


def build(k):
    L, W, H = 0.9, 0.5, 0.42
    lid = 0.06
    k.box((L, W, H - lid), (0, 0, 0), "planks_green", bevel=0.008)
    k.box((L + 0.01, W + 0.01, lid), (0, 0, H - lid), "planks_green", bevel=0.01)      # крышка чуть шире
    # рейки-обвязка по торцам и посередине длинных сторон
    for x in (-L / 2 + 0.03, L / 2 - 0.03):
        k.box((0.05, W + 0.03, H - 0.02), (x, 0, 0.01), "planks_green", bevel=0.008)
    # уголки сверху и снизу
    for x in (-L / 2 + 0.015, L / 2 - 0.015):
        for y in (-W / 2 - 0.005, W / 2 + 0.005):
            for z in (0.0, H - 0.07):
                k.box((0.07, 0.07, 0.07), (x, y, z), "rust", bevel=0.005)
    # ручки-скобы на торцах
    for s in (-1, 1):
        x = s * (L / 2 + 0.035)
        k.box((0.025, 0.2, 0.025), (x + s * 0.01, 0, 0.24), "steel", bevel=0.005)
        for y in (-0.09, 0.09):
            k.box((0.03, 0.02, 0.025), (x - s * 0.005, y, 0.24), "steel", bevel=0.004)
    # защёлки на передней стороне
    for x in (-0.25, 0.25):
        k.box((0.06, 0.02, 0.09), (x, -W / 2 - 0.013, H - lid - 0.05), "steel", bevel=0.004)
    # жёлтая полоса — маркировка ценного
    k.box((0.06, W + 0.012, 0.005), (-0.18, 0, H), "yellow", bevel=0.0)
    # трафарет спереди: калибр и счёт
    k.stencil("7,62", (0.06, -W / 2, 0.2), size=0.075)
    k.stencil("ЛПС  440 шт", (0.06, -W / 2, 0.1), size=0.03)
