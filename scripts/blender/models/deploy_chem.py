"""Химстол — по 2D-спрайту chem: длинная лабораторная тумба (серо-голубой металл) с дверцами и ящиками,
светлая столешница, на ней колбы, реторта на штативе, бутыли, справа бак-реактор. След 1,7 × 0,85."""


def build(k):
    L, W, H = 1.66, 0.78, 0.82
    k.box((L, W - 0.04, H - 0.06), (0, 0, 0.0), "paint_blue", bevel=0.012)                      # тумба
    k.box((L + 0.02, W, 0.06), (0, 0, H - 0.06), "white", bevel=0.01)                            # столешница
    for x in (-0.6, -0.2):                                                                        # дверцы слева
        k.box((0.36, 0.02, 0.6), (x, -W / 2 + 0.01, 0.08), "paint_blue", bevel=0.006)
        k.box((0.02, 0.02, 0.1), (x + 0.14, -W / 2 - 0.005, 0.38), "steel", bevel=0.003)
    for i in range(3):                                                                           # ящики справа
        k.box((0.6, 0.02, 0.18), (0.45, -W / 2 + 0.01, 0.1 + i * 0.21), "paint_blue", bevel=0.006)
        k.box((0.12, 0.02, 0.02), (0.45, -W / 2 - 0.005, 0.19 + i * 0.21), "steel", bevel=0.003)
    k.stencil("ЯД", (-0.2, -W / 2 - 0.0, 0.55), size=0.07, material="red")
    # стекло
    for x, y, r, h in ((-0.65, 0.05, 0.06, 0.16), (-0.5, 0.15, 0.045, 0.22), (-0.35, -0.05, 0.07, 0.12)):
        k.cyl(r, h, (x, y, H), "glass", segments=14, bevel=0.006, radius_top=r * 0.35)          # колбы
    k.cyl(0.012, 0.45, (-0.05, 0.25, H), "steel", segments=6, bevel=0)                           # штатив
    k.box((0.2, 0.012, 0.012), (0.0, 0.25, H + 0.38), "steel", bevel=0)
    k.cyl(0.07, 0.12, (0.06, 0.25, H + 0.22), "glass", segments=12, bevel=0.006, radius_top=0.03)   # реторта
    k.cyl(0.03, 0.05, (0.06, 0.25, H), "brass", segments=10, bevel=0.003)                        # спиртовка
    for i, x in enumerate((0.15, 0.25, 0.35)):                                                   # бутыли
        k.cyl(0.04, 0.2, (x, 0.05, H), "glass" if i != 1 else "rust_dark", segments=10, bevel=0.005, radius_top=0.02)
    k.cyl(0.17, 0.38, (0.62, 0.12, H), "tin", segments=16, bevel=0.01)                           # бак-реактор
    k.cyl(0.18, 0.04, (0.62, 0.12, H + 0.38), "steel", segments=16, bevel=0.006)
    k.cyl(0.03, 0.2, (0.62, 0.12, H + 0.42), "steel", segments=8, bevel=0.003)
    k.box((0.3, 0.25, 0.006), (-0.1, -0.15, H), "white", rot_z=-0.1, bevel=0)                   # журнал
