"""Общая основа ящиков лута: 0,97 × 0,62 × 0,6 м (как у старых моделей — ящики не подгоняются под хитбокс)."""

L, W, H = 0.94, 0.6, 0.58


def handles(k, z=0.32, mat="steel"):
    """Ручки-скобы на торцах."""
    for s in (-1, 1):
        k.box((0.025, 0.2, 0.025), (s * (L / 2 + 0.035), 0, z), mat, bevel=0.005)
        for y in (-0.09, 0.09):
            k.box((0.035, 0.02, 0.025), (s * (L / 2 + 0.012), y, z), mat, bevel=0.004)


def latches(k, z, mat="steel"):
    for x in (-0.28, 0.28):
        k.box((0.06, 0.02, 0.09), (x, -W / 2 - 0.012, z), mat, bevel=0.004)
