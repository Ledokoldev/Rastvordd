"""Слесарный верстак: по 2D-спрайту workbench — деревянная рама из бруса, толстая столешница из досок с железной окантовкой,
тумба с ящиками, полка снизу, тиски на углу. 1,6 × 0,75 × 0,9 м."""


def build(k):
    L, W, H = 1.6, 0.75, 0.86
    top_t = 0.06
    leg = 0.05
    # ножки-уголки и царги
    for x in (-L / 2 + 0.06, L / 2 - 0.06):
        for y in (-W / 2 + 0.06, W / 2 - 0.06):
            k.box((leg, leg, H - top_t), (x, y, 0), "planks", bevel=0.006)
    for y in (-W / 2 + 0.06, W / 2 - 0.06):
        k.box((L - 0.12, 0.04, 0.05), (0, y, H - top_t - 0.08), "planks", bevel=0.006)
        k.box((L - 0.12, 0.04, 0.04), (0, y, 0.18), "planks", bevel=0.006)
    # нижняя полка — фанера
    k.box((L - 0.14, W - 0.14, 0.025), (0, 0, 0.2), "plywood", bevel=0.004)
    # столешница: доски + железная полоса по переднему краю
    k.box((L, W, top_t), (0, 0, H - top_t), "planks", bevel=0.01)
    k.box((L + 0.01, 0.012, top_t + 0.01), (0, -W / 2 - 0.004, H - top_t - 0.005), "steel", bevel=0.003)
    # тумба с двумя ящиками справа
    tx = L / 2 - 0.29
    k.box((0.46, W - 0.16, 0.5), (tx, 0, 0.26), "planks", bevel=0.01)
    for z in (0.3, 0.52):
        k.box((0.4, 0.02, 0.19), (tx, -W / 2 + 0.07, z), "planks", bevel=0.006)
        k.box((0.12, 0.03, 0.02), (tx, -W / 2 + 0.055, z + 0.13), "steel", bevel=0.004)   # ручка-скоба
    # тиски на левом переднем углу: основание, губки, винт, вороток
    vx, vy, vz = -L / 2 + 0.2, -W / 2 + 0.12, H
    k.box((0.16, 0.2, 0.05), (vx, vy + 0.04, vz), "rust", bevel=0.008)
    k.box((0.16, 0.05, 0.11), (vx, vy - 0.03, vz + 0.05), "rust", bevel=0.008)
    k.box((0.16, 0.05, 0.11), (vx, vy + 0.1, vz + 0.05), "rust", bevel=0.008)
    k.cyl(0.012, 0.2, (vx, vy - 0.06, vz + 0.1), "steel", segments=8, axis="Y", bevel=0)
    k.cyl(0.008, 0.18, (vx - 0.09, vy - 0.17, vz + 0.1), "steel", segments=6, axis="X", bevel=0)
    # задняя полка-надстройка с инструментом (как на 2D)
    k.box((L, 0.18, 0.025), (0, W / 2 - 0.09, H + 0.32), "planks", bevel=0.005)
    for x in (-L / 2 + 0.03, L / 2 - 0.03):
        k.box((0.04, 0.18, 0.34), (x, W / 2 - 0.09, H), "planks", bevel=0.005)
    for x, h, m in ((-0.4, 0.14, "paint_blue"), (-0.15, 0.1, "rust"), (0.2, 0.16, "paint_green"), (0.5, 0.12, "tin")):
        k.box((0.14, 0.12, h), (x, W / 2 - 0.09, H + 0.345), m, bevel=0.008)   # банки, коробки
    k.cyl(0.05, 0.12, (0.35, 0.05, H), "tin", segments=12, bevel=0.005)          # маслёнка
    k.cyl(0.006, 0.15, (0.35, 0.05, H + 0.12), "tin", segments=6, bevel=0)
    k.box((0.3, 0.04, 0.02), (0.0, -0.1, H), "steel", rot_z=0.3, bevel=0.003)    # ножовка
