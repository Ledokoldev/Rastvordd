"""Дощатый ящик (дешёвый лут): каркас-обвязка из брусков, доски со щелями, крышка прибита."""
from _crate import H, L, W


def build(k):
    k.box((L - 0.08, W - 0.08, H - 0.04), (0, 0, 0.02), "black", bevel=0.0)             # тёмное нутро в щелях
    for i in range(4):                                                                     # доски бортов со щелями
        z = 0.03 + i * 0.135
        k.box((L, W, 0.115), (0, 0, z), "planks", bevel=0.008)
    k.box((L + 0.01, W + 0.01, 0.04), (0, 0, H - 0.04), "planks", bevel=0.008)             # крышка
    for x in (-L / 2 + 0.03, L / 2 - 0.03):                                                # обвязка по углам
        for y in (-W / 2 + 0.005, W / 2 - 0.005):
            k.box((0.06, 0.06, H + 0.01), (x, y, 0), "planks", bevel=0.008)
    for y in (-W / 2 - 0.01, W / 2 + 0.01):                                                # диагональ-раскос
        k.box((0.05, 0.02, 0.62), (0, y, 0.0), "planks", rot_z=0.0, bevel=0.006)
