"""Бак для воды: оцинкованная бочка побольше, крышка из досок на двух планках, кран внизу спереди, подставка-кирпичи.
Ø 0,9 × 1,0 м."""


def build(k):
    r, h = 0.43, 0.9
    for x, y in ((0.18, 0.18), (-0.18, 0.18), (0.18, -0.18), (-0.18, -0.18)):   # кирпичи под дно
        k.box((0.22, 0.11, 0.07), (x, y, 0), "concrete", bevel=0.006)
    z0 = 0.07
    k.cyl(r, h, (0, 0, z0), "tin", segments=22, bevel=0.01)
    for z in (z0, z0 + h - 0.03, z0 + h * 0.5):
        k.cyl(r + 0.012, 0.03, (0, 0, z), "steel", segments=22, bevel=0.005)
    # крышка: доски и две планки поперёк
    k.cyl(r + 0.02, 0.035, (0, 0, z0 + h), "planks", segments=22, bevel=0.006)
    for y in (-0.15, 0.15):
        k.box((0.82, 0.06, 0.03), (0, y, z0 + h + 0.035), "planks", bevel=0.005)
    # кран спереди внизу
    k.cyl(0.02, 0.1, (r - 0.02, 0, z0 + 0.12), "steel", segments=8, axis="X", bevel=0)
    k.box((0.02, 0.06, 0.02), (r + 0.07, 0, z0 + 0.14), "rust", bevel=0.003)
