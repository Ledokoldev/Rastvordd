"""Бочка 200 л (хранилище воды/топлива) — по 2D-спрайту barrel_200: стальная бочка в синей краске со
сколами, два зига-обруча, закатанные края, ручной насос-качалка на крышке с рукояткой и изогнутым носиком.
Ø 0,9 × 1,05 м (под след 1,2)."""


def build(k):
    r, h = 0.42, 0.88
    k.cyl(r, h, (0, 0, 0), "paint_blue", segments=22, bevel=0.012)
    for z in (0.0, h - 0.036):                                                                  # закатанные края (верх ниже крышки)
        k.cyl(r + 0.014, 0.03, (0, 0, z), "rust", segments=22, bevel=0.005)
    for z in (h * 0.33, h * 0.66):                                                              # зиги
        k.cyl(r + 0.012, 0.035, (0, 0, z), "paint_blue", segments=22, bevel=0.008)
    k.cyl(0.04, 0.02, (-0.22, 0.12, h), "steel", segments=10, bevel=0.003)                      # вторая пробка
    # насос: корпус-труба, рукоять-рычаг, носик
    k.cyl(0.045, 0.1, (0.12, -0.05, h), "rust_dark", segments=10, bevel=0.004)
    k.cyl(0.032, 0.32, (0.12, -0.05, h + 0.1), "steel", segments=10, bevel=0.003)
    k.cyl(0.04, 0.06, (0.12, -0.05, h + 0.42), "rust_dark", segments=10, bevel=0.004)
    k.box((0.34, 0.025, 0.025), (0.0, -0.05, h + 0.5), "rust", rot_z=0, bevel=0.004)          # рычаг
    k.cyl(0.02, 0.1, (-0.17, -0.05, h + 0.46), "rubber", segments=8, bevel=0)                   # ручка
    k.cyl(0.018, 0.22, (0.14, -0.05, h + 0.32), "steel", segments=8, axis="X", bevel=0)         # носик
    k.cyl(0.018, 0.08, (0.35, -0.05, h + 0.25), "steel", segments=8, bevel=0)
    k.stencil("ВОДА", (0, -r - 0.004, h * 0.5), size=0.08, wrap=r + 0.004)
