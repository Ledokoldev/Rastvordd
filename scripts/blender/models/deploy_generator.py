"""Дизель-генератор на салазках: рама из швеллера, двигатель (тёмный металл), бак сверху, решётка радиатора,
щиток управления с красной кнопкой (акцент), выхлопная труба. 1,2 × 0,7 × 1,0 м."""


def build(k):
    L, W = 1.2, 0.7
    for y in (-W / 2 + 0.05, W / 2 - 0.05):                                    # салазки
        k.box((L, 0.08, 0.08), (0, y, 0), "paint_green", bevel=0.008)
    for x in (-0.45, 0.45):
        k.box((0.08, W, 0.05), (x, 0, 0.08), "paint_green", bevel=0.006)
    k.box((0.62, 0.5, 0.48), (-0.18, 0, 0.13), "rust_dark", bevel=0.02)        # двигатель
    k.box((0.3, 0.52, 0.52), (0.36, 0, 0.13), "paint_green", bevel=0.015)      # кожух радиатора
    for i in range(6):                                                          # решётка радиатора
        k.box((0.02, 0.44, 0.03), (0.52, 0, 0.2 + i * 0.07), "steel", bevel=0.004)
    k.cyl(0.17, 0.85, (-0.42, 0, 0.78), "paint_green", segments=16, axis="X", bevel=0.01)   # бак
    k.cyl(0.04, 0.04, (0.0, 0.0, 0.94), "steel", segments=10, bevel=0.004)     # горловина
    for x in (-0.35, 0.3):                                                      # хомуты бака
        k.box((0.04, 0.37, 0.04), (x, 0, 0.6), "rust", bevel=0.004)
    k.box((0.04, 0.3, 0.24), (0.52, -0.2, 0.67), "paint_blue", bevel=0.008)    # щиток
    k.cyl(0.025, 0.03, (0.54, -0.25, 0.83), "red", segments=10, axis="X", bevel=0.003)
    k.cyl(0.018, 0.02, (0.54, -0.15, 0.83), "steel", segments=8, axis="X", bevel=0.002)
    k.cyl(0.035, 0.55, (-0.42, 0.2, 0.5), "rust", segments=10, bevel=0)        # выхлоп
    k.cyl(0.045, 0.06, (-0.42, 0.2, 1.02), "rust_dark", segments=10, bevel=0.003)
