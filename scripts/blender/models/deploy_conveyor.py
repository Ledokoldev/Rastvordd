"""Конвейер-сортировщик — по 2D-спрайту conveyor_sorter: квадратный короб из серо-зелёного металла,
сверху приёмный люк-воронка, спереди окно выдачи с резиновой лентой и две створки, сбоку мотор.
Лента идёт по +X. Квадратный след 0,85."""


def build(k):
    S, H = 0.82, 0.62
    k.box((S, S, 0.06), (0, 0, 0), "rust_dark", bevel=0.008)                                   # основание
    k.box((S - 0.06, S - 0.06, H - 0.06), (0, 0, 0.06), "paint_green", bevel=0.015)           # короб
    k.box((S - 0.02, S - 0.02, 0.04), (0, 0, H), "paint_green", bevel=0.01)                     # крышка
    k.cyl(0.2, 0.12, (-0.1, 0, H + 0.04), "steel", segments=4, bevel=0.004, radius_top=0.26, shell=0.015).rotation_euler.z = 0.785   # воронка
    k.box((0.26, 0.26, 0.01), (-0.1, 0, H + 0.04), "black", bevel=0)
    # окно выдачи с лентой (+X)
    k.box((0.04, 0.46, 0.3), (S / 2 - 0.02, 0, 0.1), "black", bevel=0)
    k.box((0.2, 0.42, 0.03), (S / 2 + 0.06, 0, 0.12), "rubber", bevel=0.008)
    for y in (-0.22, 0.22):
        k.box((0.22, 0.03, 0.08), (S / 2 + 0.06, y, 0.1), "yellow", bevel=0.005)
    for y in (-0.12, 0.12):                                                                    # створки
        k.box((0.02, 0.22, 0.12), (S / 2 - 0.01, y, 0.42), "steel", bevel=0.004)
    for x in (-0.1, 0.05):                                                                     # стрелки на крышке
        k.box((0.12, 0.03, 0.004), (x + 0.2, 0.25, H + 0.04), "white", rot_z=-0.6, bevel=0)
        k.box((0.12, 0.03, 0.004), (x + 0.2, 0.19, H + 0.04), "white", rot_z=0.6, bevel=0)
    k.cyl(0.08, 0.16, (-0.1, -S / 2 - 0.14, 0.3), "paint_blue", segments=12, axis="Y", bevel=0.008)   # мотор
